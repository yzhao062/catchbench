r"""The contrast-matrix checker must fail on every corruption it exists to catch.

Its first version passed six of seven mutations, which is worse than having no checker: a green
result on a corrupted table is what a reader trusts. Its second version still passed eight of
twenty-two, because it collected anything in the section that looked like a table row instead of
reading the rows inside the tabular.

A third failure mode arrived with the reporting-policy change that deleted the Holm column, the
verdict column, and the family table. The required-file check and the statistics-section check were
incidental effects of looping over prose patterns, so removing the patterns would have made
``check()`` return 0 for an empty paper directory and for a paper whose section label had been
deleted. ``test_an_empty_paper_directory_fails`` and ``test_a_removed_statistics_label_fails`` are
that case, and they are the two tests a naive deletion turns green.

These tests run the command line rather than calling ``check()``, so the exit status and an empty
stderr are what gets asserted: a finding printed on stdout with status 1 is a report, and a
traceback on stderr is a crash. They pin no number from the shipped record. The fixture paper is
built from what the tool itself emits, so regenerating the results moves the fixture with them, and
each corruption is described by its shape rather than by the value it damages.
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
TOOL = ROOT / "tools" / "emit_stats_table.py"

sys.path.insert(0, str(ROOT / "tools"))

import emit_stats_table as est  # noqa: E402


def _env(**overrides):
    """A clean environment, so an ambient CATCHBENCH_PAPER_DIR cannot steer these runs."""
    env = dict(os.environ)
    env.pop("CATCHBENCH_PAPER_DIR", None)
    env.update(overrides)
    return env


def _run(*args, env=None):
    return subprocess.run([sys.executable, str(TOOL), *args],
                          capture_output=True, text=True, env=env or _env())


def _check(paper):
    return _run("--check", "--paper", str(paper))


# --- the fixture paper, generated by the tool it checks ------------------------------------------

APPENDIX_TEMPLATE = """\
\\section{Comparison Groups and Ordering Tests}
\\label{app:stats}

Prose the statistics section carries, between its label and the matrix it introduces.

%(contrasts)s

\\section{Something Else}
Total & 1187 & configurations in the PRE corpus. \\\\
"""


@pytest.fixture(scope="module")
def block():
    """What ``--contrasts`` emits, which is also what ``--check`` compares the paper against."""
    done = _run("--contrasts")
    assert done.returncode == 0, done.stderr
    assert done.stderr == ""
    return done.stdout.replace("\r\n", "\n").rstrip("\n")


@pytest.fixture
def paper(tmp_path, block):
    """A minimal current paper. Each test mutates one thing and expects the check to fail."""
    (tmp_path / "09_appendix.tex").write_text(
        APPENDIX_TEMPLATE % {"contrasts": block}, encoding="utf-8")
    return tmp_path


def _read(paper):
    return (paper / "09_appendix.tex").read_text(encoding="utf-8")


def _write(paper, text):
    (paper / "09_appendix.tex").write_text(text, encoding="utf-8")


def _edit(paper, old, new, count=-1):
    text = _read(paper)
    assert old in text, f"fixture does not contain {old!r}; the test, not the tool, is wrong"
    _write(paper, text.replace(old, new) if count < 0 else text.replace(old, new, count))


def _data_rows(block_text):
    """The contrast rows, found by shape so that no test has to name a claim or a value."""
    rows = [line for line in block_text.splitlines()
            if line.endswith(r"\\") and " & " in line
            and not line.startswith(("Contrast ", r"\multicolumn", r"\caption"))]
    assert rows, "the generated block carries no contrast rows"
    return rows


def _caption_line(block_text):
    captions = [line for line in block_text.splitlines() if line.startswith(r"\caption{")]
    assert len(captions) == 1, "expected exactly one caption line in the generated block"
    return captions[0]


# --- the current paper, and the two cases a naive deletion turns green ---------------------------


def test_the_current_paper_passes(paper):
    done = _check(paper)
    assert done.returncode == 0, done.stdout
    assert "paper is current" in done.stdout
    assert done.stderr == ""


def test_an_empty_paper_directory_fails(tmp_path):
    """The trap. With no prose patterns left, a loop-shaped checker returns 0 here."""
    done = _check(tmp_path)
    assert done.returncode == 1
    assert "09_appendix.tex: missing" in done.stdout
    assert done.stderr == ""


def test_a_removed_statistics_label_fails(paper):
    """The other trap: the section boundary must be checked outside any pattern loop."""
    _edit(paper, "\\label{app:stats}\n", "")
    done = _check(paper)
    assert done.returncode == 1
    assert r"missing marker \label{app:stats}" in done.stdout
    assert done.stderr == ""


def test_a_commented_out_statistics_label_fails(paper):
    """A marker behind a percent sign is not a marker; a substring search accepted it."""
    _edit(paper, "\\label{app:stats}", "% \\label{app:stats}")
    done = _check(paper)
    assert done.returncode == 1
    assert r"missing marker \label{app:stats}" in done.stdout
    assert done.stderr == ""


def test_a_statistics_label_carrying_trailing_content_is_not_a_marker(paper):
    _edit(paper, "\\label{app:stats}", "\\label{app:stats} % and a note")
    done = _check(paper)
    assert done.returncode == 1
    assert r"missing marker \label{app:stats}" in done.stdout
    assert done.stderr == ""


def test_hidden_statistics_content_fails(paper):
    """A TeX conditional is not a comment, so a regex over the prose would not see it."""
    _edit(paper, "Prose the statistics section carries",
          "\\iffalse\nProse the statistics section carries")
    done = _check(paper)
    assert done.returncode == 1
    assert "a TeX conditional hides part of the statistics section" in done.stdout
    assert done.stderr == ""


# --- the block itself, compared byte for byte ----------------------------------------------------


def test_a_changed_cell_fails(paper, block):
    row = _data_rows(block)[0]
    damaged = re.sub(r"\d\.\d{3}", "9.999", row, count=1)
    assert damaged != row, "the mutation did not change the row"
    _edit(paper, row, damaged)
    done = _check(paper)
    assert done.returncode == 1
    assert "the contrast matrix differs from the generated block" in done.stdout
    assert "first difference at block line" in done.stdout
    assert done.stderr == ""


def test_a_missing_row_fails(paper, block):
    _edit(paper, _data_rows(block)[0] + "\n", "")
    done = _check(paper)
    assert done.returncode == 1
    assert "the contrast matrix differs from the generated block" in done.stdout
    assert done.stderr == ""


def test_a_duplicated_row_fails(paper, block):
    row = _data_rows(block)[0]
    _edit(paper, row + "\n", row + "\n" + row + "\n")
    done = _check(paper)
    assert done.returncode == 1
    assert "the contrast matrix differs from the generated block" in done.stdout
    assert done.stderr == ""


def test_reordered_rows_fail(paper, block):
    """Order carries meaning: the table is read alongside the module's declaration order."""
    first, second = _data_rows(block)[:2]
    text = _read(paper)
    _write(paper, text.replace(first, "PLACEHOLDER").replace(second, first)
           .replace("PLACEHOLDER", second))
    done = _check(paper)
    assert done.returncode == 1
    assert "the contrast matrix differs from the generated block" in done.stdout
    assert done.stderr == ""


def test_a_reindented_row_fails(paper, block):
    """The block is generated whole, so whitespace inside it is staleness rather than style."""
    row = _data_rows(block)[0]
    _edit(paper, row, "    " + row)
    done = _check(paper)
    assert done.returncode == 1
    assert done.stderr == ""


def test_a_changed_caption_fails(paper, block):
    caption = _caption_line(block)
    _edit(paper, caption,
          caption.replace(r"}\label{tab:all-contrasts}", r" An added sentence.}"
                          r"\label{tab:all-contrasts}"))
    done = _check(paper)
    assert done.returncode == 1
    assert "the contrast matrix differs from the generated block" in done.stdout
    assert done.stderr == ""


def test_a_changed_group_header_fails(paper, block):
    header = next(line for line in block.splitlines() if line.startswith(r"\multicolumn")
                  and r"\texttt{" in line)
    _edit(paper, header, header.replace(r"$\cdot$", r"$\cdot$ rewritten $\cdot$", 1))
    done = _check(paper)
    assert done.returncode == 1
    assert "the contrast matrix differs from the generated block" in done.stdout
    assert done.stderr == ""


