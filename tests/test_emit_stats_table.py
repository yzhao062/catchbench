# --- what the generated block says, and what it no longer says -------------------------------------
#
# These call the generator directly with synthetic records, because no command-line flag substitutes
# a results file and the cases below are about records the shipped file does not contain.


def _claim(group, index, metric="f1", method="paired percentile bootstrap",
           axis="run-level sampling"):
    """One synthetic contrast carrying every field the matrix prints, and nothing more.

    There is deliberately no ``verdict`` and no ``test`` key. The generator stopped reading both
    when the Holm column and the verdict column were deleted, so a record without them must still
    render; reintroducing either column turns every test in this section red at once.
    """
    return {
        "id": "%s.case%d" % (group, index),
        "family": group,
        "label": "%s: entrant %d vs floor" % (group, index),
        "metric": metric,
        "estimate": {"a": 0.5 + index / 100, "b": 0.4, "a_name": "entrant %d" % index,
                     "b_name": "floor", "difference_a_minus_b": 0.1 + index / 100},
        "interval": {"low": 0.01, "high": 0.2, "level": 0.95, "method": method, "axis": axis},
    }


DATA = {
    "claims": (
        [_claim("alpha_group", i) for i in range(3)]
        + [_claim("beta_group", i) for i in range(2)]
    ),
    "comparison_families": [
        {"id": "alpha_group", "size": 3, "description": "Three alpha contrasts."},
        {"id": "beta_group", "size": 2, "description": "Two beta contrasts."},
    ],
}

CLUSTERED = "task-clustered stratified percentile bootstrap"


def test_every_claim_appears_in_the_generated_block():
    generated = est.contrasts(DATA)
    for claim in DATA["claims"]:
        assert est._tex(claim["label"]) in generated, claim["id"]


def test_the_block_prints_no_adjusted_p_and_no_verdict():
    """The reporting-policy change, pinned where it would regress: the two deleted columns."""
    generated = est.contrasts(DATA)
    for word in ("Holm", "Verdict", "separates", "unresolved"):
        assert word not in generated, word


def test_the_column_count_agrees_across_the_preamble_header_and_rules(block):
    """Deleting a column leaves three places to update, and a stale one breaks the table."""
    lines = block.splitlines()
    preamble = next(line for line in lines if line.startswith(r"\begin{longtable}"))
    spec = preamble[preamble.index("{", len(r"\begin{longtable")) + 1:preamble.rindex("}")]
    spec = re.sub(r">\{[^}]*\}", "", spec).replace("@{}", "")
    assert len(re.findall(r"p\{[^}]*\}|[lcr]", spec)) == est._COLUMNS, spec
    header = next(line for line in lines if line.startswith("Contrast "))
    assert header.count("&") == est._COLUMNS - 1, header
    rules = [line for line in lines if line.startswith(r"\multicolumn")]
    assert rules and all(r"\multicolumn{%d}" % est._COLUMNS in line for line in rules)
    for row in _data_rows(block):
        assert row.count("&") == est._COLUMNS - 1, row


def test_a_group_header_states_scope_metric_and_construction():
    generated = est.contrasts(DATA)
    rule = r"\multicolumn{%d}{@{}p{%s}@{}}" % (est._COLUMNS, est._HEADER_RULE)
    assert (rule + r"{\texttt{alpha\_group} $\cdot$ Three alpha contrasts. $\cdot$ f1 $\cdot$ "
            r"paired percentile bootstrap, run-level sampling}\\" in generated)


def test_a_single_construction_group_leaves_its_rows_unannotated():
    generated = est.contrasts(DATA)
    assert "interval:" not in generated
    assert r"alpha\_group: entrant 0 vs floor & 0.500" in generated


def test_a_group_mixing_interval_constructions_names_it_on_every_row():
    """post_detection_auc is this shape: two task-clustered rows among five run-level ones.

    A header naming one construction over rows built two ways is a false statement in the paper,
    so the header defers and each row says which construction produced its interval.
    """
    claims = [_claim("mixed_group", 0),
              _claim("mixed_group", 1, method=CLUSTERED, axis="task-cluster resampling"),
              _claim("mixed_group", 2)]
    data = {"claims": claims,
            "comparison_families": [{"id": "mixed_group", "size": 3, "description": "Mixed."}]}
    generated = est.contrasts(data)
    assert "interval construction on each row" in generated
    assert "(interval: paired percentile bootstrap, run-level sampling)" in generated
    assert "(interval: %s, task-cluster resampling)" % CLUSTERED in generated
    for claim in claims:
        assert "%s (interval:" % est._tex(claim["label"]) in generated


def test_a_group_with_several_metrics_names_the_metric_on_each_row():
    """Three rows reading the same pair with three different numbers would name nothing."""
    claims = [_claim("mixed_family", i, metric=m)
              for i, m in enumerate(("top1", "top3", "mrr"))]
    for claim in claims:
        claim["label"] = "exec-rank vs position"
    data = {"claims": claims,
            "comparison_families": [{"id": "mixed_family", "size": 3, "description": "Mixed."}]}
    generated = est.contrasts(data)
    for metric in ("top1", "top3", "mrr"):
        assert "exec-rank vs position (%s)" % metric in generated
    assert "metric on each row" in generated


def test_a_group_mixing_both_names_both_on_the_row():
    claims = [_claim("both_group", 0, metric="top1"),
              _claim("both_group", 1, metric="mrr", method=CLUSTERED,
                     axis="task-cluster resampling")]
    data = {"claims": claims,
            "comparison_families": [{"id": "both_group", "size": 2, "description": "Both."}]}
    generated = est.contrasts(data)
    assert "(top1; interval: paired percentile bootstrap, run-level sampling)" in generated
    assert "(mrr; interval: %s, task-cluster resampling)" % CLUSTERED in generated


def test_a_group_whose_declared_size_disagrees_refuses_to_render():
    """A group that declares three contrasts and carries two must not print a short table."""
    data = {"claims": [_claim("alpha_group", 0)],
            "comparison_families": [{"id": "alpha_group", "size": 3, "description": "Three."}]}
    with pytest.raises(SystemExit, match="declares 3 contrasts"):
        est.contrasts(data)


def test_a_group_with_no_claims_refuses_to_render():
    data = {"claims": [],
            "comparison_families": [{"id": "ghost_group", "size": 0, "description": "None."}]}
    with pytest.raises(SystemExit, match="carry none"):
        est.contrasts(data)


def test_a_claim_whose_group_is_not_declared_refuses_to_render():
    """The table is the printed home of every claim, so a claim with no home is not a short table."""
    data = {"claims": [_claim("alpha_group", 0), _claim("orphan_group", 0)],
            "comparison_families": [{"id": "alpha_group", "size": 1, "description": "One."}]}
    with pytest.raises(SystemExit, match="no printed home"):
        est.contrasts(data)


def test_a_label_needing_unhandled_escaping_refuses_to_render():
    """Guessing at a backslash or a brace would emit a row that compiles into something else."""
    claim = _claim("alpha_group", 0)
    claim["label"] = r"entrant \textbf{x} vs floor"
    data = {"claims": [claim],
            "comparison_families": [{"id": "alpha_group", "size": 1, "description": "One."}]}
    with pytest.raises(SystemExit, match="needs escaping"):
        est.contrasts(data)


def test_ampersand_and_percent_in_a_label_are_escaped():
    claim = _claim("alpha_group", 0)
    claim["label"] = "Who&When 25% vs floor"
    data = {"claims": [claim],
            "comparison_families": [{"id": "alpha_group", "size": 1, "description": "One."}]}
    assert r"Who\&When 25\% vs floor" in est.contrasts(data)


def test_an_unsafe_group_id_refuses_to_render():
    broken = json.loads(json.dumps(DATA))
    broken["comparison_families"][0]["id"] = "alpha{group}"
    broken["claims"] = [dict(claim, family="alpha{group}") if claim["family"] == "alpha_group"
                        else claim for claim in broken["claims"]]
    with pytest.raises(SystemExit, match="needs escaping"):
        est.contrasts(broken)


def test_no_generated_line_carries_a_literal_tab():
    r"""A mangled backslash turns \times into a tab and prints ``imes`` in the PDF."""
    assert "\t" not in est.contrasts(DATA)


def test_the_group_header_uses_no_bar_character():
    """A bare | is an em dash under OT1, which is both wrong here and a dash the style forbids."""
    assert "|" not in est.contrasts(DATA)


def test_the_inventory_counts_records_not_distinct_ids():
    """Two groups that share an id are still two groups in the printed inventory."""
    data = {"claims": [{}] * 4,
            "comparison_families": [{"id": "same_id", "size": 2, "description": "First."},
                                    {"id": "same_id", "size": 2, "description": "Second."}]}
    assert est.inventory(data) == {"groups": 2, "contrasts": 4}
