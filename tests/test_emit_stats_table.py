def test_sentinels_in_the_wrong_order_fail(paper, block):
    """Each sentinel appears once and the span is inverted, so the count check does not catch it."""
    lines = block.splitlines()
    assert lines[0] == est._CONTRASTS_BEGIN and lines[-1] == est._CONTRASTS_END
    inverted = "\n".join([lines[-1]] + lines[1:-1] + [lines[0]])
    _write(paper, APPENDIX_TEMPLATE % {"contrasts": inverted})
    done = _check(paper)
    assert done.returncode == 1
    assert "end marker precedes its begin marker" in done.stdout
    assert done.stderr == ""


def test_a_missing_block_fails(paper):
    text = _read(paper)
    _write(paper, text[:text.index(est._CONTRASTS_BEGIN)])
    done = _check(paper)
    assert done.returncode == 1
    assert done.stderr == ""


def test_an_unrelated_total_row_outside_the_block_is_ignored(paper):
    """The PRE corpus table's ``Total & 1187`` sits outside the block and must not be read."""
    assert "Total & 1187" in _read(paper)
    assert _check(paper).returncode == 0


